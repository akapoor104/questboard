// Builds db/seed.sql from seed/base.json and seed/starter-plan.json.
// Run after editing the seed files:   node scripts/build-seed-sql.mjs
// The output is pasted into the Supabase SQL editor once (docs/02-setup-guide.md, part 3).
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));
const base = read('seed/base.json');
const plan = read('seed/starter-plan.json');

const tag = '$qbseed$';
for (const doc of [base, plan]) {
  if (JSON.stringify(doc).includes(tag)) throw new Error('seed data must not contain ' + tag);
}
const sql = `-- Questboard seed data. GENERATED by scripts/build-seed-sql.mjs: edit seed/*.json, not this file.
-- Safe to run more than once: rows that already exist are left alone, and the
-- starter plan is skipped if the child already has cards or goals.
-- Run db/migrations/*.sql and admin_setup(...) first.

select qb.load(${tag}${JSON.stringify(base)}${tag}::jsonb, false) as loaded;

select qb.load_starter_plan(
  (select id from qb.children order by created_at, id limit 1),
  ${tag}${JSON.stringify({ goals: plan.goals, cards: plan.cards })}${tag}::jsonb) as starter_plan;
`;
writeFileSync(new URL('db/seed.sql', root), sql);
console.log(`db/seed.sql written (${sql.length} bytes): ${base.tables.library_items.length} library items, ` +
  `${base.tables.words.length} words, ${base.tables.encouragements.length} encouragements, ` +
  `${plan.goals.length} goals, ${plan.cards.reduce((n, c) => n + (c.count ?? 1), 0)} cards`);
